// Writes what the web app needs: ABIs (src/chain/abi.js) and per-network addresses
// (src/chain/deployments.js + contracts/deployments/<chainId>.json).
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const ART = path.resolve(__dirname, '..', 'artifacts', 'contracts');
const DEP_DIR = path.resolve(__dirname, '..', 'deployments');

function exportAbi() {
  const abi = (n) => JSON.parse(fs.readFileSync(path.join(ART, `${n}.sol`, `${n}.json`), 'utf8')).abi;
  const out = `// AUTO-GENERATED by contracts/scripts/export.js from the compiled contracts — do not edit.\n` +
    `export const HAMSTER_ABI = ${JSON.stringify(abi('SqueekHamster'))};\n` +
    `export const ARENA_ABI = ${JSON.stringify(abi('SqueekArena'))};\n`;
  fs.writeFileSync(path.join(ROOT, 'html', 'src', 'chain', 'abi.js'), out);
  // Creation bytecode, so the web page (deploy.html) can deploy through MetaMask.
  const art = (n) => JSON.parse(fs.readFileSync(path.join(ART, `${n}.sol`, `${n}.json`), 'utf8'));
  fs.writeFileSync(path.join(ROOT, 'html', 'src', 'chain', 'bytecode.js'),
    `// AUTO-GENERATED by contracts/scripts/export.js (optimizer 200, viaIR; see contracts/hardhat.config.js) — do not edit.
` +
    `export const HAMSTER_BYTECODE = '${art('SqueekHamster').bytecode}';
` +
    `export const ARENA_BYTECODE = '${art('SqueekArena').bytecode}';
`);
}

/** Rebuild src/chain/deployments.js from every contracts/deployments/*.json. */
function exportDeployments() {
  const all = {};
  if (fs.existsSync(DEP_DIR)) for (const f of fs.readdirSync(DEP_DIR)) {
    if (!f.endsWith('.json')) continue;
    const d = JSON.parse(fs.readFileSync(path.join(DEP_DIR, f), 'utf8'));
    all[d.chainId] = d;
  }
  fs.writeFileSync(path.join(ROOT, 'html', 'src', 'chain', 'deployments.js'),
    `// AUTO-GENERATED by contracts/scripts/export.js (deploy writes contracts/deployments/<chainId>.json).\n` +
    `export const DEPLOYMENTS = ${JSON.stringify(all, null, 2)};\n`);
}

function saveDeployment(d) {
  fs.mkdirSync(DEP_DIR, { recursive: true });
  fs.writeFileSync(path.join(DEP_DIR, `${d.chainId}.json`), JSON.stringify(d, null, 2) + '\n');
  exportDeployments();
}

module.exports = { exportAbi, exportDeployments, saveDeployment };
if (require.main === module) { exportAbi(); exportDeployments(); console.log('exported abi + deployments'); }
