#!/usr/bin/env node
// Headless autopilot: the same full flow the web page runs, on the command line.
//
//   node scripts/autopilot.mjs --network localhost --rounds 1 --slots 100
//   node scripts/autopilot.mjs --network localhost --rounds 0            # forever
//   node scripts/autopilot.mjs --network sepolia  --rounds 1 --slots 20
//   node scripts/autopilot.mjs --publish ...            # also write contracts/deployments/<id>.json
//   node scripts/autopilot.mjs --rpc http://chain:8545 --publish-json /published/deployments.json
//   node scripts/autopilot.mjs --dev-wallets                # ví dev của node local (LOCAL_DEV_MNEMONIC)
//
// The burner phrase lives in contracts/.autopilot/keystore.json (gitignored). The first run
// creates it and then stops to tell you the runner address to fund — on a local Hardhat
// node it funds itself from a dev account instead, so the whole thing is one command.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ethers } from '../../html/src/vendor/ethers.min.js';
import { Autopilot, DEFAULTS, prepareLocalChain } from '../../html/src/chain/autopilot.js';
import { createKeystore, devKeystore, isDevPhrase, isPublicKeystore, devPhrase, importKeystore,
         exportKeystore, runnerWallet, botWallets } from '../../html/src/chain/wallets.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const CHAIN = resolve(HERE, '..');
const KS_PATH = resolve(CHAIN, '.autopilot', 'keystore.json');
// The autopilot keeps its own deployments. `contracts/deployments/` is committed and describes
// the deployment the project publishes; a throwaway local run must not overwrite it (doing
// so silently repoints every page and every other script at a burner-owned contract).
// --publish copies the run's addresses there on purpose.
const DEP_DIR = resolve(CHAIN, '.autopilot', 'deployments');
const REPO_DEP_DIR = resolve(CHAIN, 'deployments');
const NETS = {
  localhost: { chainId: 31337, rpc: process.env.RPC_URL || 'http://127.0.0.1:8545' },
  sepolia: { chainId: 11155111, rpc: process.env.SEPOLIA_RPC_URL || 'https://ethereum-sepolia-rpc.publicnode.com' },
};
// Phrase of the local node's dev accounts (LOCAL_DEV_MNEMONIC in contracts/.env), chain 31337 only.
try { await import('dotenv/config'); } catch { /* env already set */ }

function arg(name, dflt) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] !== undefined && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : dflt;
}
const flag = (name) => process.argv.includes(`--${name}`);

/** Deployment store backed by contracts/deployments/<chainId>.json (same files the web app reads). */
const fileStore = {
  get(chainId) {
    const p = resolve(DEP_DIR, `${chainId}.json`);
    return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
  },
  set(d) {
    mkdirSync(DEP_DIR, { recursive: true });
    writeFileSync(resolve(DEP_DIR, `${d.chainId}.json`), JSON.stringify(d, null, 2) + '\n');

    // --publish-json <file>: the map the served site reads at load (see chainReady in
    // src/chain/client.js). In Docker this file lives on a volume the web container
    // serves, which is how a container-deployed contract becomes visible to visitors.
    const out = arg('publish-json', process.env.PUBLISH_JSON || '');
    if (out) {
      let all = {};
      try { all = JSON.parse(readFileSync(out, 'utf8')); } catch { /* first write */ }
      all[d.chainId] = d;
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, JSON.stringify(all, null, 2) + '\n');
      console.log(`đã publish địa chỉ ra ${out}`);
    }
    if (!flag('publish')) return;
    // --publish: make this the deployment the repo (and therefore every page) points at.
    mkdirSync(REPO_DEP_DIR, { recursive: true });
    writeFileSync(resolve(REPO_DEP_DIR, `${d.chainId}.json`), JSON.stringify(d, null, 2) + '\n');
    const all = {};
    for (const f of readdirSync(REPO_DEP_DIR)) {
      if (f.endsWith('.json')) { const j = JSON.parse(readFileSync(resolve(REPO_DEP_DIR, f), 'utf8')); all[j.chainId] = j; }
    }
    writeFileSync(resolve(CHAIN, '..', 'html', 'src', 'chain', 'deployments.js'),
      '// AUTO-GENERATED by contracts/scripts/export.js (deploy writes contracts/deployments/<chainId>.json).\n'
      + `export const DEPLOYMENTS = ${JSON.stringify(all, null, 2)};\n`);
    console.log(`--publish: đã ghi địa chỉ vào contracts/deployments/${d.chainId}.json và src/chain/deployments.js`);
  },
};

function loadOrCreateKeystore(slots) {
  // --dev-wallets: the public Hardhat phrase. Same addresses on every machine, and the
  // first twenty already hold 10000 ETH on a local node, so there is nothing to fund and
  // nothing to copy between computers. Worthless by design — local chain only.
  if (flag('dev-wallets')) return devKeystore({ botCount: Math.max(slots, DEFAULTS.slots) });
  if (existsSync(KS_PATH)) return importKeystore(readFileSync(KS_PATH, 'utf8'));
  const k = createKeystore({ botCount: Math.max(slots, DEFAULTS.slots), label: 'squeek autopilot' });
  mkdirSync(dirname(KS_PATH), { recursive: true });
  writeFileSync(KS_PATH, exportKeystore(k), { mode: 0o600 });
  console.log(`Đã tạo keystore mới: ${KS_PATH}`);
  return k;
}

/** On a local Hardhat node, move ETH from a dev account into the runner so nothing is manual. */
async function autoFundLocal(provider, runner, wantEth) {
  const HARDHAT_PHRASE = devPhrase();
  if (!HARDHAT_PHRASE) throw new Error('set LOCAL_DEV_MNEMONIC in contracts/.env to auto-fund the runner on a local node');
  const dev = ethers.HDNodeWallet.fromPhrase(HARDHAT_PHRASE, '', "m/44'/60'/0'/0/0").connect(provider);
  const have = await provider.getBalance(runner.address);
  const want = ethers.parseEther(wantEth);
  if (have >= want) return have;
  const devBal = await provider.getBalance(dev.address);
  if (devBal < want) throw new Error(`tài khoản dev chỉ có ${ethers.formatEther(devBal)} ETH`);
  await (await dev.sendTransaction({ to: runner.address, value: want - have })).wait();
  const now = await provider.getBalance(runner.address);
  console.log(`Nạp ví runner từ tài khoản dev Hardhat: ${ethers.formatEther(now)} ETH`);
  return now;
}

async function main() {
  const netName = arg('network', 'localhost');
  const net = NETS[netName];
  if (!net) throw new Error(`mạng không hỗ trợ: ${netName} (localhost | sepolia)`);
  const slots = Number(arg('slots', DEFAULTS.slots));
  const roundsArg = Number(arg('rounds', 1));
  const rounds = roundsArg === 0 ? Infinity : roundsArg;

  // cacheTimeout -1 disables ethers' short-lived RPC cache: the autopilot polls block
  // numbers and arena status in a loop, and a cached answer would make it wait forever.
  // batchMaxCount 1 sends one JSON-RPC request per call: the autopilot fires dozens of
  // transactions at once and a batched send is where a single bad entry takes the rest
  // of the batch down with it ("could not coalesce error").
  net.rpc = arg('rpc', net.rpc);                 // --rpc http://chain:8545 (compose, docker network)
  const provider = new ethers.JsonRpcProvider(net.rpc, net.chainId,
    { staticNetwork: true, cacheTimeout: -1, batchMaxCount: 1 });
  // ethers polls for receipts every 4 s by default. On a local chain that is the single
  // biggest cost of a round — a hundred waits spread over four batches is over a minute of
  // doing nothing — so poll as fast as the local node mines.
  provider.pollingInterval = net.chainId === 31337 ? 250 : 4000;
  const keystore = loadOrCreateKeystore(slots);
  if (isPublicKeystore(keystore) && net.chainId !== 31337)
    throw new Error('Kho ví này dùng cụm từ CÔNG KHAI (--dev-wallets): '
      + 'chỉ chạy trên chain local (31337), vì trên testnet chung các địa chỉ này bị bot quét sạch '
      + 'trong vài phút. Bỏ cờ đó để dùng kho ví riêng trong contracts/.autopilot/.');
  const runner = runnerWallet(keystore, provider);

  const options = {
    slots,
    reserveHuman: !flag('no-reserve'),
    commitSeconds: Number(arg('commit', netName === 'localhost' ? 20 : 180)),
    topUpLeadSeconds: Number(arg('top-up-lead', netName === 'localhost' ? 5 : 30)),
    concurrency: Number(arg('concurrency', netName === 'localhost' ? 25 : 8)),
    pollMs: netName === 'localhost' ? 400 : 4000,
    preset: Number(arg('preset', 0)),
    perBotEth: arg('per-bot', '0.002'),
  };

  console.log(`mạng ${netName} (${net.chainId}) · runner ${runner.address} · ${slots} chỗ · ${rounds === Infinity ? 'chạy liên tục' : rounds + ' vòng'}`);

  if (net.chainId === 31337) {
    // 1000 ms, not less: Hardhat forces every block's timestamp at least one second past
    // the previous one, so a faster interval makes the chain's clock outrun the wall clock
    // and phase 1 closes sooner than its advertised length.
    const blockMs = Number(arg('block-ms', 1000));
    const ok = await prepareLocalChain(provider, blockMs);
    console.log(ok ? `node local: interval mining ${blockMs}ms (tắt automine)`
                   : 'node local: không đặt được interval mining — mỗi tx một block, kéo dài phase 1 cho đủ.');
    if (!ok) options.commitSeconds = Math.max(options.commitSeconds, slots + 30);
  }

  // Funding: automatic on the local chain, manual (a faucet) everywhere else.
  // What one round costs the runner: a top-up for every bot plus its own gas. On the local
  // chain we hand it a much larger float so a long soak never stops to be refilled.
  const needEth = (Number(options.perBotEth) * slots + 0.05).toFixed(4);
  if (net.chainId === 31337) await autoFundLocal(provider, runner, (Number(needEth) * 4 + 10).toFixed(4));
  const bal = await provider.getBalance(runner.address);
  console.log(`số dư runner: ${ethers.formatEther(bal)} ETH (cần ~${needEth})`);
  if (bal === 0n) {
    console.log(`\nNạp ETH vào ${runner.address} rồi chạy lại lệnh này.`);
    process.exitCode = 1;
    return;
  }

  const t0 = Date.now();
  const ap = new Autopilot({ provider, keystore, chainId: net.chainId, store: fileStore, options,
    onEvent: ({ kind, phase, text }) => {
      const tag = kind === 'phase' ? `\x1b[36m[${phase}]\x1b[0m` : kind === 'err' ? '\x1b[31m✗\x1b[0m'
        : kind === 'warn' ? '\x1b[33m!\x1b[0m' : kind === 'ok' ? '\x1b[32m✓\x1b[0m' : kind === 'round' ? '' : ' ';
      console.log(`${String(((Date.now() - t0) / 1000).toFixed(1)).padStart(6)}s ${tag} ${text}`);
    } });

  for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => { console.log('\ndừng sau vòng hiện tại…'); ap.stop(); });
  const out = await ap.run({ rounds, redeploy: flag('redeploy') });
  console.log(`\nxong ${out.length} vòng trong ${((Date.now() - t0) / 1000).toFixed(1)}s`);
}

main().catch((e) => {
  console.error('\n' + (e?.shortMessage || e?.message || e));
  if (process.env.DEBUG) console.error(e);
  process.exitCode = 1;
});
