#!/usr/bin/env node
// Generates contracts/HamsterGenome.sol from the game's own genome tables
// (src/core/hamster.js + src/core/appearance.js), so the contract can never drift from
// the simulator. Run after any change to the item table:  node scripts/gen-genome.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ITEM_STATS, STAT_KEYS, STAT_BASE, HEAD_KEYS, BACK_KEYS, FIRST_NAMES, LAST_NAMES, GENOME_VERSION } from '../../html/src/core/hamster.js';
import { FUR_COLORS, FUR_PATTERNS, FACE_EYES, OUTFIT_BODY } from '../../html/src/core/appearance.js';

const OUT = fileURLToPath(new URL('../contracts/HamsterGenome.sol', import.meta.url));
const hex = (keys, table) => keys.map((k) => STAT_KEYS.map((s) => table[k][s].toString(16).padStart(2, '0')).join('')).join('');
const strArr = (name, list) => `  function ${name}(uint256 i) internal pure returns (string memory) {
    string[${list.length}] memory a = [${list.map((s) => `"${s}"`).join(', ')}];
    return a[i];
  }`;
// Card colours per fur (used by the on-chain SVG only; the game uses the AGY art).
const FUR_HEX = { honey_orange: 'f2a54a', russet_brown: 'a8643a', ash_grey: '9aa0a6', taro_lilac: 'b79ad8', snow_cream: 'f6ead2',
                  golden_butter: 'f5cf55', charcoal_spike: '4a4a52', maple_cinnamon: 'c06a3c' };

const sol = `// SPDX-License-Identifier: MIT
// AUTO-GENERATED by contracts/scripts/gen-genome.mjs from src/core/hamster.js — do not edit.
// Genome v${GENOME_VERSION}: DNA word k = (dna >> 16k) & 0xffff.
//   w0 fur  w1 pattern  w2 eyes  w3 body  w4 head (0 = none)  w5 back (0 = none)
//   w9..w11 name.  Stats = ${STAT_BASE} + body + head + back, order ${STAT_KEYS.join(', ')}.
pragma solidity ^0.8.24;

library HamsterGenome {
  uint8 internal constant GENOME_VERSION = ${GENOME_VERSION};
  uint8 internal constant STAT_BASE = ${STAT_BASE};
  uint8 internal constant N_FUR = ${FUR_COLORS.length};
  uint8 internal constant N_PATTERN = ${FUR_PATTERNS.length};
  uint8 internal constant N_EYES = ${FACE_EYES.length};
  uint8 internal constant N_BODY = ${OUTFIT_BODY.length};
  uint8 internal constant N_HEAD = ${HEAD_KEYS.length};
  uint8 internal constant N_BACK = ${BACK_KEYS.length};
  // 5 bytes per item: ${STAT_KEYS.join(', ')}
  bytes internal constant BODY_STATS = hex"${hex(OUTFIT_BODY, ITEM_STATS.body)}";
  bytes internal constant HEAD_STATS = hex"${hex(HEAD_KEYS, ITEM_STATS.head)}";
  bytes internal constant BACK_STATS = hex"${hex(BACK_KEYS, ITEM_STATS.back)}";

  struct Traits {
    uint8 fur; uint8 pattern; uint8 eyes; uint8 body; uint8 head; uint8 back;
    uint8 str; uint8 agi; uint8 arm; uint8 vit; uint8 per;
  }

  function word(uint256 dna, uint256 k) internal pure returns (uint256) { return (dna >> (16 * k)) & 0xffff; }

  function decode(uint256 dna) internal pure returns (Traits memory t) {
    t.fur = uint8(word(dna, 0) % N_FUR);
    t.pattern = uint8(word(dna, 1) % N_PATTERN);
    t.eyes = uint8(word(dna, 2) % N_EYES);
    t.body = uint8(word(dna, 3) % N_BODY);
    t.head = uint8(word(dna, 4) % N_HEAD);
    t.back = uint8(word(dna, 5) % N_BACK);
    uint256 b = uint256(t.body) * 5; uint256 h = uint256(t.head) * 5; uint256 k = uint256(t.back) * 5;
    t.str = STAT_BASE + uint8(BODY_STATS[b]) + uint8(HEAD_STATS[h]) + uint8(BACK_STATS[k]);
    t.agi = STAT_BASE + uint8(BODY_STATS[b + 1]) + uint8(HEAD_STATS[h + 1]) + uint8(BACK_STATS[k + 1]);
    t.arm = STAT_BASE + uint8(BODY_STATS[b + 2]) + uint8(HEAD_STATS[h + 2]) + uint8(BACK_STATS[k + 2]);
    t.vit = STAT_BASE + uint8(BODY_STATS[b + 3]) + uint8(HEAD_STATS[h + 3]) + uint8(BACK_STATS[k + 3]);
    t.per = STAT_BASE + uint8(BODY_STATS[b + 4]) + uint8(HEAD_STATS[h + 4]) + uint8(BACK_STATS[k + 4]);
  }

  function name(uint256 dna) internal pure returns (string memory) {
    return string.concat(firstName(word(dna, 9) % ${FIRST_NAMES.length}), lastName(word(dna, 10) % ${LAST_NAMES.length}),
                         _u(word(dna, 11) % 90 + 10));
  }

${strArr('furName', FUR_COLORS)}
${strArr('furHex', FUR_COLORS.map((f) => FUR_HEX[f] || 'cccccc'))}
${strArr('patternName', FUR_PATTERNS)}
${strArr('eyesName', FACE_EYES)}
${strArr('bodyName', OUTFIT_BODY)}
${strArr('headName', HEAD_KEYS)}
${strArr('backName', BACK_KEYS)}
${strArr('firstName', FIRST_NAMES)}
${strArr('lastName', LAST_NAMES)}

  function _u(uint256 v) private pure returns (string memory) {
    if (v == 0) return "0";
    bytes memory b = new bytes(3); uint256 n;
    while (v > 0) { b[2 - n] = bytes1(uint8(48 + (v % 10))); v /= 10; n++; }
    bytes memory o = new bytes(n);
    for (uint256 i = 0; i < n; i++) o[i] = b[3 - n + i];
    return string(o);
  }
}
`;
writeFileSync(OUT, sol);
console.log(`wrote ${OUT}`);
